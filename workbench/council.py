"""Transparent deterministic review roles, not independent language models."""
import uuid
from .store import now

ROLES = [
    {"id": "orchestrator", "name": "Архитектор исследований", "focus": "Декомпозиция вопроса и границы результата"},
    {"id": "evidence", "name": "Аудитор доказательств", "focus": "Первоисточники, воспроизводимость, противоречия"},
    {"id": "biology", "name": "Биологический рецензент", "focus": "Различие моделей и целого взрослого организма"},
    {"id": "causality", "name": "Методолог причинности", "focus": "Контроли, альтернативные объяснения и неопределённость"},
    {"id": "computation", "name": "Вычислительный советник", "focus": "Применимость ML, численных методов и квантовых моделей"},
    {"id": "security", "name": "Архитектор изоляции", "focus": "Полномочия плагинов и границы доверия"},
    {"id": "reproducibility", "name": "Инженер воспроизводимости", "focus": "Версии, параметры, seeds и журнал"},
    {"id": "delivery", "name": "Инженер реализации", "focus": "Проверяемые результаты и критерии приёмки"},
]


def advisors():
    return [dict(role, kind="rule_based") for role in ROLES]


def review(question, sources):
    text = question.casefold()
    speculative = any(t in text for t in ("горяев", "гаряев", "волновой геном", "микролептон", "торсион"))
    biological = any(t in text for t in ("геном", "эволю", "организм", "genom", "epigen", "эпиген", "organ"))
    quantum = any(t in text for t in ("квант", "quantum", "qpu"))
    count = len(sources)
    assessments = {
      "orchestrator": ("Вопрос принят для исследовательской декомпозиции. Роли применяют фиксированные правила; это не заключение группы независимых экспертов.",
                        ["Определить измеримый исследовательский результат", "Разделить обзор, вычислительный тест и проверку на данных"]),
      "evidence": (f"Прикреплено источников: {count}. Само наличие ссылки не подтверждает утверждение; содержание автоматически не проверялось.",
                   ["Сопоставить каждое утверждение с первоисточником", "Отметить независимые репликации и отрицательные результаты"]),
      "biology": (("Модель не доказывает возможность целенаправленного изменения взрослого организма. Прогноз целого организма здесь не реализован." if biological else "Биологическая применимость не следует из вычислительной демонстрации."),
                  ["Указать масштаб и область валидности модели", "Не переносить результат игрушечной симуляции на организм"]),
      "causality": (("Спекулятивная гипотеза требует операционального определения и независимой проверки; механизм не считается установленным." if speculative else "Корреляции и результаты симуляции сами по себе не устанавливают причинность."),
                    ["Сформулировать опровержимое утверждение", "Сравнить с базовой моделью и альтернативными объяснениями"]),
      "computation": (("Квантовый симулятор демонстрирует алгоритм; преимущество перед классическим методом и доступ к QPU не предполагаются." if quantum else "Начать с воспроизводимой классической базовой модели; сложность модели должна оправдываться проверкой на данных."),
                      ["Зафиксировать метрику и вычислительный бюджет", "Оценить устойчивость результата к параметрам"]),
      "security": ("Встроенный плагин запускается отдельным процессом с лимитами. Это не песочница уровня контейнера или виртуальной машины.",
                   ["Исполнять только зарегистрированные встроенные плагины", "Разделять внешние источники и команды исполнения"]),
      "reproducibility": ("Для проверки результата нужны параметры, версия кода, seed и происхождение данных. Журнал хешей не заменяет внешнюю подпись.",
                          ["Сохранить параметры запуска и версии", "Экспортировать исследовательский снимок"]),
      "delivery": ("Критерий завершения этой версии — работающий исследовательский процесс и проверяемый отчёт. Биологическая цель требует отдельной научной валидации.",
                   ["Запустить подходящую вычислительную демонстрацию", "Записать ограничения и следующую проверяемую задачу"]),
    }
    entries = []
    for role in advisors():
        assessment, actions = assessments[role["id"]]
        entries.append(dict(role, assessment=assessment, actions=actions))
    return {"id": str(uuid.uuid4()), "question": question, "mode": "rule_based",
            "verdict": "Требуется проверка гипотез и источников; автоматического научного подтверждения нет.",
            "advisors": entries, "source_ids": [s["id"] for s in sources],
            "next_steps": ["Уточнить гипотезу и критерий её опровержения", "Проверить первоисточники", "Выполнить воспроизводимый вычислительный тест", "Проверить ограничения и сохранить отчёт"],
            "created_at": now()}
